"""Pydantic schemas and data contracts for agent communication."""

from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class SectionPlan(BaseModel):
    """Blueprint for a single section within the article."""
    heading: str = Field(..., description="Clear, descriptive section heading")
    key_points: List[str] = Field(
        default_factory=list,
        description="2-4 technical subtopics, concepts, or code takeaways"
    )
    target_words: int = Field(
        default=50,
        description="Target word budget for this specific section"
    )


class BlogPlan(BaseModel):
    """Strategic structural outline generated by the Planner Agent."""
    title: str = Field(..., description="Publication-ready article headline")
    target_audience: str = Field(
        default="Computer Science Undergraduate",
        description="Target reader persona and technical comprehension level"
    )
    total_target_words: int = Field(
        default=200,
        description="Overall target word count across all sections"
    )
    sections: List[SectionPlan] = Field(
        ...,
        description="Ordered sequence of section blueprints forming the complete blog post"
    )


class ValidationReport(BaseModel):
    """Rubric critique and grading report generated by the Validator Agent."""
    passed: bool = Field(
        ...,
        description="True if the draft satisfies all rubric gates, False if revision is required"
    )
    overall_score: int = Field(
        ...,
        ge=0,
        le=100,
        description="Objective quality score between 0 and 100"
    )
    word_count_actual: int = Field(
        ...,
        description="Total measured word count of the current draft"
    )
    word_count_status: str = Field(
        default="OK",
        description="'TOO_SHORT', 'TOO_LONG', or 'OK'"
    )
    missing_sections: List[str] = Field(
        default_factory=list,
        description="Any headings from the plan that were completely omitted or altered in the draft"
    )
    critiques: List[str] = Field(
        default_factory=list,
        description="List of specific defects or rubric failures identified"
    )
    actionable_feedback: List[str] = Field(
        default_factory=list,
        description="Exact, concrete revision instructions for the Writer to resolve on the next turn"
    )


class AgentTraceStep(BaseModel):
    """Single execution step record for observability and UI rendering."""
    step_id: int
    iteration: int
    agent_name: str
    phase: str  # "PLAN", "DRAFT", "VALIDATE", "TOOL_CALL"
    content_snippet: str
    tokens_used: int = 0
    latency_ms: float = 0.0
    tool_calls: Optional[List[Dict[str, Any]]] = None


class PipelineRunState(BaseModel):
    """Full execution state across the entire multi-agent lifecycle."""
    topic: str
    provider: str
    model: str
    plan: Optional[BlogPlan] = None
    current_draft: str = ""
    draft_history: List[str] = Field(default_factory=list)
    validation_reports: List[ValidationReport] = Field(default_factory=list)
    trace_steps: List[AgentTraceStep] = Field(default_factory=list)
    total_iterations: int = 0
    final_status: str = "PENDING"  # "PASSED", "MAX_RETRIES_EXCEEDED", "ERROR"
